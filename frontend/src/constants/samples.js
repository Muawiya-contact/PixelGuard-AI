/** "Gemini_Generated_Image_ab12.jpg" -> "Gemini Generated Image ab12" */
function titleFromFilename(file) {
  const base = file.replace(/\.[^.]+$/, '').replace(/[_-]+/g, ' ').replace(/\s+/g, ' ').trim()
  return base.charAt(0).toUpperCase() + base.slice(1)
}

/** Group every discovered file under its folder, newest config order first. */
export const SAMPLE_CATEGORIES = Object.entries(
  Object.entries(FILES).reduce((acc, [path, url]) => {
    const parts = path.split('/')
    const file = parts.pop()
    const category = parts.pop()
    ;(acc[category] ||= []).push({ file, url, ...(DESCRIPTIONS[file] || {}) })
    return acc
  }, {}),
).map(([id, samples]) => {
  const meta = CATEGORY_META[id] || {
    title: titleFromFilename(id),
    blurb: '',
    expects: '',
    tone: 'text-muted bg-raised border-line',
    order: 99,
  }
  return {
    id,
    ...meta,
    samples: samples
      .map((s) => ({ title: titleFromFilename(s.file), detail: '', ...s }))
      .sort((a, b) => a.file.localeCompare(b.file)),
  }
}).sort((a, b) => a.order - b.order)
