/**
 * Sample gallery configuration.
 *
 * Images are DISCOVERED, not listed. Every file under
 * `src/assets/samples/<category>/` is picked up automatically by Vite's glob,
 * so dropping a file into a folder makes it appear with no edit here — and
 * removing one makes it disappear without leaving a dead entry behind.
 *
 * They live under `src/assets/` rather than `public/` precisely so this
 * enumeration is possible: nothing can list a directory in `public/` at
 * runtime, which is why a hand-maintained array drifted out of sync with the
 * folder in the first place.
 *
 * DESCRIPTIONS below is optional per-file copy. A file with no entry still
 * shows, captioned from its filename. Anything written here states what the
 * file ACTUALLY contains — verified with the metadata parser, not inferred from
 * the folder it sits in. A category name says what the group is meant to
 * exercise; PixelGuard still reports whatever it finds, and it may disagree.
 */

